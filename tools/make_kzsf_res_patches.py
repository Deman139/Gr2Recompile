"""Writes patches/Killzone_Shadow_Fall.xml: render resolution patches for CUSA00190 v01.81.

Sites (eboot vaddr, without the 0x400000 base); each line carries its signature (Pattern/At) so
patches.py finds it by content.
  render: renderer settings, fields +0x380 width, +0x384 height, +0x388/+0x38c half size
          (init 0xfc1a20, reset 0xfc20c0).
  scene:  {-1, -1, 1920, 1080} at 0x8e6256: the size the scene render targets are created with
          (G-buffer, depth, and the 1/2..1/64 chains derived from it).
  arena:  memory region table (0x32ba70): +0xb0 is the GPU render target arena (0x19f00000);
          the last region (+0x140) is the rest of direct memory, total - 0x1a720000 - others.
          +0x110 is "RW Textures (Garlic)" (8 MiB; at 4K its 1/8-size targets overflow it: "Out of
          memory while creating texture"). Larger regions take D from that constant and the patch
          asks for D more direct memory (Note "DMEM to N MB", patches.patch_requirements), so the
          RenderData pool keeps its size. Region names are at 0x11aa319..0x11aa3ad.
Other {0, 0, 1920, 1080} rectangles (0x50a0d3, 0xe80a9b, 0xe843b7, 0xfc39e3, 0xfc8773, 0xfc87ff)
are not needed; patching them all made level loads hang.
The FOV is a live setting of the loader (src/mouse_hook.h gow3_fov_site), not a patch here.
Usage: make_kzsf_res_patches.py <eboot.elf> <out.xml>
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'scripts'))
from patches import eboot_image  # noqa: E402

BASE = 0x400000
# (site, pattern length, [(offset, field)]): w/h full size, hw/hh half size, arena/rest memory.
SITES = [(0xfc1a88, 30, [(2, 'hw'), (6, 'hh'), (16, 'w'), (26, 'h')]),
         (0xfc20cd, 30, [(6, 'w'), (16, 'h'), (22, 'hw'), (26, 'hh')]),
         (0x8e6256, 24, [(3, 'w'), (10, 'h')]),
         (0x32bb34, 12, [(7, 'arena')]),
         (0x32bb4a, 12, [(7, 'rw')]),
         (0x32bb64, 12, [(2, 'rest')])]
ARENA, RW, REST = 0x19f00000, 0x800000, -0x1a720000
NATIVE = {'w': 1920, 'h': 1080, 'hw': 960, 'hh': 540, 'arena': ARENA, 'rw': RW, 'rest': REST & 0xffffffff}
# name: (width, height, extra video pool MiB, extra RW textures MiB): both grow with the pixel
# count (415 and 8 MiB at 1080p).
SIZES = {'720p': (1280, 720, 0, 0), '1440p': (2560, 1440, 384, 8), '1800p': (3200, 1800, 768, 16),
         '4K': (3840, 2160, 1280, 32)}
# Upscaler quality modes (launcher, scripts/upscale_modes.py): render sizes below 1080p that
# FSR / DLSS take to the output. Named by size; no extra memory below 1080p.
SIZES.update({f'{w}x{h}': (w, h, 0, 0) for w, h in
              ((1856, 1044), (1708, 960), (1600, 900), (1488, 836), (1280, 720), (1120, 630), (1066, 600),
               (960, 540), (852, 480), (640, 360))})
def lines(image, size):
    arena, rw = size[2] << 20, size[3] << 20
    values = {'w': size[0], 'h': size[1], 'hw': size[0] // 2, 'hh': size[1] // 2,
              'arena': ARENA + arena, 'rw': RW + rw, 'rest': (REST - arena - rw) & 0xffffffff}
    out = []
    for site, length, fields in SITES:
        pattern = image[site:site + length]
        for offset, field in fields:
            old = int.from_bytes(image[site + offset:site + offset + 4], 'little')
            if old != NATIVE[field]:
                raise SystemExit(f'{site + offset:#x}: expected {NATIVE[field]:#x}, found {old:#x}')
            if values[field] == old:
                continue
            out.append(f'            <Line Type="bytes" Address="{BASE + site + offset:#010x}" '
                       f'Value="{values[field].to_bytes(4, "little").hex()}" '
                       f'Pattern="{pattern.hex(" ")}" At="{offset}"/>')
    return out


def main():
    image = eboot_image(Path(sys.argv[1]).read_bytes())
    parts = ['<?xml version="1.0"?>',
             '<!-- kzsf_pc: generated by tools/make_kzsf_res_patches.py for CUSA00190 v01.81. -->',
             '<Patch>', '    <TitleID>', '        <ID>CUSA00190</ID>', '    </TitleID>']
    for name, size in SIZES.items():
        extra = size[2] + size[3]
        memory = (f' Grows the GNM video pool by {size[2]} MB and RW textures by {size[3]} MB.'
                  f' Requires setting DMEM to {extra} MB or more.' if extra else '')
        parts.append(f'    <Metadata Title="Killzone Shadow Fall" Name="Resolution Patch - {name}" '
                     f'Note="Game render resolution {size[0]}x{size[1]}.{memory}" '
                     f'Author="lesca" PatchVer="0.1" AppVer="01.81" AppElf="eboot.bin" isEnabled="false">')
        parts += ['        <PatchList>', *lines(image, size), '        </PatchList>', '    </Metadata>']
    parts.append('</Patch>')
    Path(sys.argv[2]).write_text('\n'.join(parts) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
